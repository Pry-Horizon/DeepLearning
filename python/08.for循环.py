"""
1.for循环：
    一种轮询遍历
    ========================
    for 元素 in 待处理的数据集：
        循环体代码
    else:
        循环结束时执行的代码
    =========================

"""

msg = input("请输入需要遍历的字符串：")
for s in msg: #s表示遍历出来的元素
    print(f"元素：{s}")
else:
    print("遍历完成！")

#案例1.计算1-100之间所有奇数之和
sum = 0;
for i in range(1,100,2):
    sum+=i
else:
    print(f"1-100所有奇数之和为{sum}")

#案例2.计算100-500之间所有3的倍数之和
sum = 0
for i in range(100,501):
    if i%3 == 0:
        sum += i;
else:
    print(f"100-500所有3的倍数之和为{sum}")